SELECT Z.AUTHOR_ID,
       Z.AUTHOR_NAME,
       Z.CATEGORY,
       SUM(Z.TOTAL_SALES) AS TOTAL_SALES
  FROM(
SELECT SUM(C.SALES) * A.PRICE AS TOTAL_SALES,
       A.BOOK_ID,
       A.PRICE,
       B.AUTHOR_NAME,
       A.CATEGORY,
       A.AUTHOR_ID
  FROM BOOK A
 INNER JOIN AUTHOR B ON A.AUTHOR_ID = B.AUTHOR_ID
 INNER JOIN BOOK_SALES C ON A.BOOK_ID = C.BOOK_ID
 WHERE C.SALES_DATE BETWEEN '2022-01-01' AND '2022-01-31'
 GROUP BY A.AUTHOR_ID, A.BOOK_ID
 ORDER BY A.AUTHOR_ID, A.CATEGORY DESC) Z
 GROUP BY Z.AUTHOR_ID, Z.CATEGORY