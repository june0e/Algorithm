-- 중고거래 USED_GOODS_USER / 중고 거래 게시판정보 USED_GOODS_BOARD
SELECT B.USER_ID,  -- 회원ID
       B.NICKNAME, -- 닉네임
       SUM(A.PRICE)
  FROM USED_GOODS_BOARD A
 INNER JOIN USED_GOODS_USER B on A.WRITER_ID = B.USER_ID
 WHERE A.STATUS = 'DONE'
 GROUP BY B.USER_ID, B.NICKNAME
 HAVING SUM(A.PRICE) >= 700000
 ORDER BY SUM(A.PRICE) ASC